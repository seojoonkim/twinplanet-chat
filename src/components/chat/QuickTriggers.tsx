// ─────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────

function shuffled<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
}

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]!;
}

function buildInitialState(allIds: string[]): { shownIds: string[]; poolIds: string[] } {
  const s = shuffled(allIds);
  return {
    shownIds: s.slice(0, 3),
    poolIds: s.slice(3),
  };
}

// ─────────────────────────────────────────────
// Component
// ─────────────────────────────────────────────

interface Props {
  idolId: string;
  onTrigger: (message: string) => void;
  disabled?: boolean;
}

export default function QuickTriggers({ idolId, onTrigger, disabled }: Props) {
  const allQuestions = IDOL_QUESTIONS[idolId];
  const allIds = allQuestions?.map((q) => q.id) ?? [];

  const [state, setState] = useState<{ shownIds: string[]; poolIds: string[] }>(() =>
    buildInitialState(allIds)
  );

  if (!allQuestions || allQuestions.length === 0) return null;

  const questionMap = Object.fromEntries(allQuestions.map((q) => [q.id, q]));

  const handleClick = (question: QuestionDef) => {
    if (disabled) return;

    // 1. 5가지 variant 중 랜덤 선택 → onTrigger
    const variantIdx = Math.floor(Math.random() * question.variants.length);
    const msg: string = question.variants[variantIdx] as string;
    onTrigger(msg);

    // 2. shown에서 클릭된 것 제거 + pool에서 1개 추가 (풀 비면 전체 리셋)
    setState((prev) => {
      const nextShown = prev.shownIds.filter((id) => id !== question.id);

      if (prev.poolIds.length === 0) {
        // 풀이 비어있음: 클릭된 것 제외한 전체로 새 풀 구성
        const resetPool = shuffled(allIds.filter((id) => id !== question.id));
        // 보여줄 슬롯이 3개 미만이면 풀에서 보충
        const slotsNeeded = 3 - nextShown.length;
        const toAdd = resetPool.slice(0, slotsNeeded);
        const remaining = resetPool.slice(slotsNeeded);
        return {
          shownIds: [...nextShown, ...toAdd],
          poolIds: remaining,
        };
      } else {
        // 풀에서 랜덤 1개 선택
        const shuffledPool = shuffled(prev.poolIds);
        const [picked, ...remaining] = shuffledPool;
        return {
          shownIds: picked ? [...nextShown, picked] : nextShown,
          poolIds: remaining,
        };
      }
    });
  };

  const handleRandomClick = () => {
    if (disabled) return;
    const pool = RANDOM_QUESTIONS[idolId];
    if (pool && pool.length > 0) {
      onTrigger(pickRandom(pool));
    }
  };

  return (
    <div className="w-full px-4 py-2 flex flex-wrap gap-2 justify-center bg-transparent">
      {state.shownIds.map((id) => {
        const q = questionMap[id];
        if (!q) return null;
        return (
          <button
            key={id}
            onClick={() => handleClick(q)}
            disabled={disabled}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-gray-200 text-[13px] font-medium text-gray-700 whitespace-nowrap shrink-0 shadow-sm transition-all duration-150 hover:shadow-md hover:border-gray-300 active:scale-95 disabled:opacity-40 disabled:cursor-not-allowed"
          >
            <span>{q.emoji}</span>
            <span>{q.label}</span>
          </button>
        );
      })}
      {/* 🎲 랜덤질문 버튼: 항상 맨 오른쪽 고정 */}
      <button
        onClick={handleRandomClick}
        disabled={disabled}
        className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-white border border-gray-200 text-[13px] font-medium text-gray-700 whitespace-nowrap shrink-0 shadow-sm transition-all duration-150 hover:shadow-md hover:border-gray-300 active:scale-95 disabled:opacity-40 disabled:cursor-not-allowed"
      >
        <span>🎲</span>
        <span>랜덤질문</span>
      </button>
    </div>
  );
}
